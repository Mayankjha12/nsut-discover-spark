DateTime _in(int days) {
  final now = DateTime.now();
  return DateTime(now.year, now.month, now.day + days, 23, 59);
}

DateTime _ago(int days) {
  final now = DateTime.now();
  return DateTime(now.year, now.month, now.day - days, 10, 0);
}

